import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { extname, join, resolve } from 'node:path';

const projectRoot = resolve(import.meta.dirname, '..');
const sourceRoot = resolve(projectRoot, 'packages/huangli/src');
const destination = resolve(sourceRoot, 'zh-hant-data.js');
const hanPattern = /\p{Script=Han}+/gu;
const phrases = new Set();
const characters = new Set();

function collect(path) {
  if (path === destination) return;
  const text = readFileSync(path, 'utf8');
  for (const match of text.matchAll(hanPattern)) {
    if (match[0].length > 1) phrases.add(match[0]);
    for (const character of match[0]) characters.add(character);
  }
}

function walk(path) {
  for (const entry of readdirSync(path, { withFileTypes: true })) {
    const child = join(path, entry.name);
    if (entry.isDirectory()) walk(child);
    else if (extname(entry.name) === '.js') collect(child);
  }
}

walk(sourceRoot);

// These labels originate in js-ephemeris-lite and enter HuangliDay output,
// so they are not discoverable by scanning this package alone.
for (const source of [
  '小寒','大寒','立春','雨水','惊蛰','春分','清明','谷雨',
  '立夏','小满','芒种','夏至','小暑','大暑','立秋','处暑',
  '白露','秋分','寒露','霜降','立冬','小雪','大雪','冬至',
  '朔','上弦','望','下弦',
]) {
  if (source.length > 1) phrases.add(source);
  for (const character of source) characters.add(character);
}

// ICU handles contextual variants for complete labels. These overrides retain
// project terminology where a single character would otherwise be ambiguous.
const overrides = new Map([
  ['黄历', '黃曆'],
  ['万年历', '萬年曆'],
  ['农历', '農曆'],
  ['公历', '公曆'],
  ['日历', '日曆'],
  ['月历', '月曆'],
  ['历法', '曆法'],
  ['钟表', '鐘錶'],
  ['天干', '天干'],
  ['干支', '干支'],
  ['天后', '天后'],
  ['皇后', '皇后'],
  ['太后', '太后'],
  ['斗', '斗'],
  ['丑', '丑'],
]);
for (const source of overrides.keys()) {
  if (source.length > 1) phrases.add(source);
  for (const character of source) characters.add(character);
}

const inputs = [...characters, ...phrases].sort((a, b) => a.localeCompare(b, 'zh-CN'));
const swiftSource = String.raw`
import Foundation
let transform = StringTransform("Simplified-Traditional")
while let line = readLine() {
  print(line.applyingTransform(transform, reverse: false) ?? line)
}
`;
const cachePath = '/tmp/huangli-lite-swift-module-cache';
mkdirSync(cachePath, { recursive: true });
const converted = execFileSync('swift', ['-e', swiftSource], {
  cwd: projectRoot,
  env: { ...process.env, CLANG_MODULE_CACHE_PATH: cachePath, SWIFT_MODULECACHE_PATH: cachePath },
  input: `${inputs.join('\n')}\n`, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024,
}).trimEnd().split('\n');

const phraseMap = {};
const characterMap = {};
for (const [index, source] of inputs.entries()) {
  const target = overrides.get(source) ?? converted[index] ?? source;
  if (source === target) continue;
  if (source.length === 1) characterMap[source] = target;
  else phraseMap[source] = target;
}
for (const [source, target] of overrides) if (source.length > 1) phraseMap[source] = target;

const sortedPhrases = Object.entries(phraseMap).sort((a, b) => (
  b[0].length - a[0].length || a[0].localeCompare(b[0], 'zh-CN')
));
writeFileSync(destination,
  `// Generated by scripts/build-huangli-zh-hant.mjs.\n`
  + `export const ZH_HANT_PHRASES = ${JSON.stringify(sortedPhrases)};\n`
  + `export const ZH_HANT_CHARACTERS = ${JSON.stringify(characterMap)};\n`);
console.log(`Generated ${sortedPhrases.length} phrases and ${Object.keys(characterMap).length} characters: ${destination}`);
