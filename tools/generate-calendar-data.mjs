#!/usr/bin/env node

import { readFile, writeFile, mkdir } from 'node:fs/promises';

const SOURCE = '/Users/rzliu/Developer/OpenDestiny/taiyin-ephemeris/src/chinese_calendar/historical_calendar_data.h';
const OUTPUT = new URL('../src/generated/historical-calendar-data.js', import.meta.url);
const source = await readFile(SOURCE, 'utf8');

function required(match, label) {
  if (!match) throw new Error(`cannot parse ${label}`);
  return match;
}

function integerConstant(name) {
  const match = required(
    new RegExp(`${name}\\s*=\\s*(?:INT64_C\\()?(-?\\d+)`).exec(source),
    name,
  );
  return Number(match[1]);
}

function stringConstant(name) {
  return required(new RegExp(`${name}\\s*=\\s*"([^"]+)"`).exec(source), name)[1];
}

function arrayBody(name) {
  return required(new RegExp(`${name}\\s*=\\s*\\{\\{([\\s\\S]*?)\\}\\};`).exec(source), name)[1];
}

function segments(name) {
  return [...arrayBody(name).matchAll(
    /\{(\d+)u,\s*(\d+)u,\s*INT64_C\((-?\d+)\),\s*INT64_C\((-?\d+)\)\}/g,
  )].map(match => match.slice(1).map(Number));
}

function segment(name) {
  const match = required(new RegExp(
    `${name}\\s*=\\s*\\{\\s*(\\d+)u,\\s*(\\d+)u,\\s*INT64_C\\((-?\\d+)\\),\\s*INT64_C\\((-?\\d+)\\)\\s*\\}`,
  ).exec(source), name);
  return match.slice(1).map(Number);
}

function int64Array(name) {
  return [...arrayBody(name).matchAll(/INT64_C\((-?\d+)\)/g)].map(match => Number(match[1]));
}

function uint16Array(name) {
  return [...arrayBody(name).matchAll(/\b(\d+)\b/g)].map(match => Number(match[1]));
}

function uint64AsUint32(name) {
  const result = [];
  for (const match of arrayBody(name).matchAll(/UINT64_C\((0x[0-9a-fA-F]+)\)/g)) {
    const word = BigInt(match[1]);
    result.push(Number(word & 0xffffffffn), Number((word >> 32n) & 0xffffffffn));
  }
  return result;
}

function typed(name, values) {
  return `${name}: new Uint32Array(${JSON.stringify(values)})`;
}

const data = {
  civilDayScale: integerConstant('kHistoricalCivilDayScale'),
  civilOffsetMinutes: integerConstant('kHistoricalCivilOffsetMinutes'),
  profileEndJd: integerConstant('kHistoricalProfileEndJd'),
  rankBlockEvents: integerConstant('kHistoricalResidualRankBlockEvents'),
  profileSha256: stringConstant('kHistoricalProfileSha256'),
  newMoon: {
    firstPhaseIndex: integerConstant('kHistoricalNewMoonFirstPhaseIndex'),
    eventCount: integerConstant('kHistoricalNewMoonEventCount'),
    firstCivilDay: integerConstant('kHistoricalNewMoonFirstCivilDay'),
    lastCivilDay: integerConstant('kHistoricalNewMoonLastCivilDay'),
    exactSegments: segments('kHistoricalNewMoonExactSegments'),
    tail: segment('kHistoricalNewMoonTail'),
    residualMask: uint64AsUint32('kHistoricalNewMoonResidualMask'),
    residualSigns: uint64AsUint32('kHistoricalNewMoonResidualSigns'),
    residualRank: uint16Array('kHistoricalNewMoonResidualRank'),
  },
  solarTerm: {
    firstPhaseIndex: integerConstant('kHistoricalSolarTermFirstPhaseIndex'),
    eventCount: integerConstant('kHistoricalSolarTermEventCount'),
    firstCivilDay: integerConstant('kHistoricalSolarTermFirstCivilDay'),
    lastCivilDay: integerConstant('kHistoricalSolarTermLastCivilDay'),
    exactSegments: segments('kHistoricalSolarTermExactSegments'),
    tail: segment('kHistoricalSolarTermTail'),
    phaseTicks: int64Array('kSolarTermPhaseTicks'),
    residualMask: uint64AsUint32('kHistoricalSolarTermResidualMask'),
    residualSigns: uint64AsUint32('kHistoricalSolarTermResidualSigns'),
    residualRank: uint16Array('kHistoricalSolarTermResidualRank'),
  },
};

const renderProfile = profile => `{
  firstPhaseIndex: ${profile.firstPhaseIndex},
  eventCount: ${profile.eventCount},
  firstCivilDay: ${profile.firstCivilDay},
  lastCivilDay: ${profile.lastCivilDay},
  exactSegments: ${JSON.stringify(profile.exactSegments)},
  tail: ${JSON.stringify(profile.tail)},
  ${profile.phaseTicks ? `phaseTicks: ${JSON.stringify(profile.phaseTicks)},\n  ` : ''}${typed('residualMask', profile.residualMask)},
  ${typed('residualSigns', profile.residualSigns)},
  residualRank: new Uint16Array(${JSON.stringify(profile.residualRank)}),
}`;

const output = `// Generated by tools/generate-calendar-data.mjs from the C++ historical profile.\n// 64-bit packed words are split low-32 then high-32 for exact JS bit access.\nexport const HISTORICAL_CALENDAR_DATA = Object.freeze({
  civilDayScale: ${data.civilDayScale},
  civilOffsetMinutes: ${data.civilOffsetMinutes},
  profileEndJd: ${data.profileEndJd},
  rankBlockEvents: ${data.rankBlockEvents},
  profileSha256: ${JSON.stringify(data.profileSha256)},
  newMoon: Object.freeze(${renderProfile(data.newMoon)}),
  solarTerm: Object.freeze(${renderProfile(data.solarTerm)}),
});\n`;

await mkdir(new URL('../src/generated/', import.meta.url), { recursive: true });
await writeFile(OUTPUT, output);
console.log(JSON.stringify({
  output: OUTPUT.pathname,
  newMoonEvents: data.newMoon.eventCount,
  solarTermEvents: data.solarTerm.eventCount,
  packedBytes: 4 * (
    data.newMoon.residualMask.length + data.newMoon.residualSigns.length
    + data.solarTerm.residualMask.length + data.solarTerm.residualSigns.length
  ),
}, null, 2));
